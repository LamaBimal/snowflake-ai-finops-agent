-- 04_daily_metrics.sql : one row per application per day
CREATE OR REPLACE VIEW AI_FINOPS.ANALYTICS.DAILY_METRICS AS
SELECT
    TO_DATE(CONVERT_TIMEZONE('UTC', USAGE_TIME))          AS USAGE_DATE,  -- UTC days
    SOURCE,
    APPLICATION,
    SUM(CREDITS)                                          AS CREDITS,
    SUM(TOTAL_TOKENS)                                     AS TOTAL_TOKENS,
    SUM(INPUT_TOKENS)                                     AS INPUT_TOKENS,
    SUM(OUTPUT_TOKENS)                                    AS OUTPUT_TOKENS,
    SUM(REQUEST_COUNT)                                    AS REQUESTS,
    SUM(RETRY_COUNT)                                      AS RETRIES,
    SUM(INPUT_TOKENS)  / NULLIF(SUM(REQUEST_COUNT), 0)    AS INPUT_TOKENS_PER_REQUEST,
    SUM(OUTPUT_TOKENS) / NULLIF(SUM(REQUEST_COUNT), 0)    AS OUTPUT_TOKENS_PER_REQUEST,
    SUM(CREDITS)       / NULLIF(SUM(REQUEST_COUNT), 0)    AS CREDITS_PER_REQUEST,
    SUM(INPUT_TOKENS)  / NULLIF(SUM(OUTPUT_TOKENS), 0)    AS INPUT_OUTPUT_RATIO,
    SUM(RETRY_COUNT)   / NULLIF(SUM(REQUEST_COUNT), 0)    AS RETRY_RATIO,
    SUM(DUPLICATE_COUNT) / NULLIF(SUM(REQUEST_COUNT), 0)  AS DUPLICATE_RATIO,
    SUM(AGENT_STEPS)   / NULLIF(SUM(REQUEST_COUNT), 0)    AS AVG_AGENT_STEPS,
    SUM(CACHEABLE_INPUT_TOKENS) / NULLIF(SUM(INPUT_TOKENS), 0) AS STATIC_CONTEXT_RATIO,
    AVG(LATENCY_MS)                                       AS AVG_LATENCY_MS,
    APPROX_PERCENTILE(LATENCY_MS, 0.95)                   AS P95_LATENCY_MS,
    SUM(FAILED_COUNT)  / NULLIF(SUM(REQUEST_COUNT), 0)    AS FAILURE_RATE,
    LISTAGG(DISTINCT FUNCTION_NAME, ',')                  AS FUNCTIONS,
    MODE(MODEL_NAME)                                      AS PRIMARY_MODEL,
    MAX(RAG_TOP_K)                                        AS RAG_TOP_K
FROM AI_FINOPS.ANALYTICS.AI_USAGE_METRICS
GROUP BY 1, 2, 3;
