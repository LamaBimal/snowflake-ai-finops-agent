-- 05_anomaly_detection.sql : rolling 7-day Z-score detection across several metrics

-- Long format: one row per application / day / metric
CREATE OR REPLACE VIEW AI_FINOPS.DETECTION.V_ZSCORE AS
WITH D AS (
    SELECT USAGE_DATE, SOURCE, APPLICATION, PRIMARY_MODEL,
        CREDITS::FLOAT AS CREDITS, TOTAL_TOKENS::FLOAT AS TOTAL_TOKENS, REQUESTS::FLOAT AS REQUESTS,
        INPUT_TOKENS_PER_REQUEST::FLOAT AS INPUT_TOKENS_PER_REQUEST,
        OUTPUT_TOKENS_PER_REQUEST::FLOAT AS OUTPUT_TOKENS_PER_REQUEST,
        CREDITS_PER_REQUEST::FLOAT AS CREDITS_PER_REQUEST,
        DUPLICATE_RATIO::FLOAT AS DUPLICATE_RATIO,
        AVG_AGENT_STEPS::FLOAT AS AVG_AGENT_STEPS,
        STATIC_CONTEXT_RATIO::FLOAT AS STATIC_CONTEXT_RATIO
    FROM AI_FINOPS.ANALYTICS.DAILY_METRICS
),
LONG AS (
    SELECT USAGE_DATE, SOURCE, APPLICATION, PRIMARY_MODEL, METRIC, VALUE
    FROM D
    UNPIVOT (VALUE FOR METRIC IN (   -- NULL metrics (e.g. real telemetry) are dropped by UNPIVOT
        CREDITS, TOTAL_TOKENS, REQUESTS,
        INPUT_TOKENS_PER_REQUEST, OUTPUT_TOKENS_PER_REQUEST, CREDITS_PER_REQUEST,
        DUPLICATE_RATIO, AVG_AGENT_STEPS, STATIC_CONTEXT_RATIO))
),
BASE AS (
    SELECT *,
        AVG(VALUE)    OVER (PARTITION BY SOURCE, APPLICATION, METRIC ORDER BY USAGE_DATE
                            ROWS BETWEEN 7 PRECEDING AND 1 PRECEDING) AS BASELINE_AVG,
        STDDEV(VALUE) OVER (PARTITION BY SOURCE, APPLICATION, METRIC ORDER BY USAGE_DATE
                            ROWS BETWEEN 7 PRECEDING AND 1 PRECEDING) AS BASELINE_STD,
        COUNT(VALUE)  OVER (PARTITION BY SOURCE, APPLICATION, METRIC ORDER BY USAGE_DATE
                            ROWS BETWEEN 7 PRECEDING AND 1 PRECEDING) AS BASELINE_DAYS
    FROM LONG
)
SELECT *,
    -- floor std at 5% of the mean so near-constant series don't explode the score;
    -- ratio metrics also get an absolute floor (0.005) so tiny wiggles in a ~1% ratio stay normal
    (VALUE - BASELINE_AVG) / NULLIF(GREATEST(BASELINE_STD, 0.05 * ABS(BASELINE_AVG),
        IFF(METRIC IN ('DUPLICATE_RATIO', 'STATIC_CONTEXT_RATIO'), 0.005, 0)), 0)        AS Z_SCORE,
    (VALUE - BASELINE_AVG) / NULLIF(BASELINE_AVG, 0)                                     AS PCT_CHANGE,
    CASE WHEN BASELINE_DAYS < 5 THEN 'INSUFFICIENT_HISTORY'
         WHEN ABS(Z_SCORE) >= 3 THEN 'HIGH'
         WHEN ABS(Z_SCORE) >= 2 THEN 'WARNING'
         ELSE 'NORMAL' END                                                               AS SEVERITY
FROM BASE;

CREATE TABLE IF NOT EXISTS AI_FINOPS.DETECTION.ANOMALIES (
    ANOMALY_ID     VARCHAR DEFAULT UUID_STRING(),
    USAGE_DATE     DATE,
    SOURCE         VARCHAR,
    APPLICATION    VARCHAR,
    METRIC         VARCHAR,
    PRIMARY_MODEL  VARCHAR,
    EXPECTED_VALUE FLOAT,
    OBSERVED_VALUE FLOAT,
    PCT_CHANGE     FLOAT,
    Z_SCORE        FLOAT,
    SEVERITY       VARCHAR,
    DETECTOR       VARCHAR DEFAULT 'ZSCORE_7D',
    DETECTED_AT    TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Idempotent: re-running for the same window updates rather than duplicates
CREATE OR REPLACE PROCEDURE AI_FINOPS.DETECTION.SP_DETECT_ANOMALIES(LOOKBACK_DAYS NUMBER)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
    MERGE INTO AI_FINOPS.DETECTION.ANOMALIES T
    USING (
        SELECT * FROM AI_FINOPS.DETECTION.V_ZSCORE
        WHERE SEVERITY IN ('WARNING', 'HIGH')
          AND USAGE_DATE >= DATEADD('DAY', -:LOOKBACK_DAYS, CURRENT_DATE())
    ) S
    ON  T.USAGE_DATE = S.USAGE_DATE AND T.SOURCE = S.SOURCE
    AND T.APPLICATION = S.APPLICATION AND T.METRIC = S.METRIC AND T.DETECTOR = 'ZSCORE_7D'
    WHEN MATCHED THEN UPDATE SET
        EXPECTED_VALUE = S.BASELINE_AVG, OBSERVED_VALUE = S.VALUE, PCT_CHANGE = S.PCT_CHANGE,
        Z_SCORE = S.Z_SCORE, SEVERITY = S.SEVERITY, PRIMARY_MODEL = S.PRIMARY_MODEL,
        DETECTED_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT
        (USAGE_DATE, SOURCE, APPLICATION, METRIC, PRIMARY_MODEL,
         EXPECTED_VALUE, OBSERVED_VALUE, PCT_CHANGE, Z_SCORE, SEVERITY)
    VALUES
        (S.USAGE_DATE, S.SOURCE, S.APPLICATION, S.METRIC, S.PRIMARY_MODEL,
         S.BASELINE_AVG, S.VALUE, S.PCT_CHANGE, S.Z_SCORE, S.SEVERITY);
    RETURN 'merged ' || SQLROWCOUNT || ' anomaly rows';
END;
$$;
