-- 03_usage_metrics.sql : unified request-level metrics (real + synthetic)
-- Real sources: AI functions (02), Cortex Agents and Cortex Search (11). Run 11 before this file.
CREATE OR REPLACE VIEW AI_FINOPS.ANALYTICS.AI_USAGE_METRICS AS
WITH U AS (
    SELECT 'REAL' AS SOURCE, * FROM AI_FINOPS.ANALYTICS.V_CORTEX_USAGE
    UNION ALL
    SELECT 'REAL' AS SOURCE, * FROM AI_FINOPS.ANALYTICS.V_CORTEX_AGENT_USAGE
    UNION ALL
    SELECT 'REAL' AS SOURCE, * FROM AI_FINOPS.ANALYTICS.V_CORTEX_SEARCH_USAGE
    UNION ALL
    SELECT 'SYNTHETIC' AS SOURCE,
           USAGE_TIME, QUERY_ID, APPLICATION, USER_ID, ROLE_NAME, FUNCTION_NAME, MODEL_NAME,
           INPUT_TOKENS, OUTPUT_TOKENS, CREDITS, REQUEST_COUNT, RETRY_COUNT, RAG_TOP_K,
           DUPLICATE_COUNT, AGENT_STEPS, CACHEABLE_INPUT_TOKENS,
           NULL::NUMBER AS LATENCY_MS, NULL::NUMBER AS FAILED_COUNT   -- not simulated
    FROM AI_FINOPS.RAW.SYNTHETIC_USAGE
)
SELECT
    U.*,
    INPUT_TOKENS + OUTPUT_TOKENS                                  AS TOTAL_TOKENS,
    (INPUT_TOKENS + OUTPUT_TOKENS) / NULLIF(REQUEST_COUNT, 0)     AS TOKENS_PER_REQUEST,
    CREDITS / NULLIF(REQUEST_COUNT, 0)                            AS CREDITS_PER_REQUEST
FROM U;
