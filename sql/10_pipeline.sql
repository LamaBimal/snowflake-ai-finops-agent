-- 10_pipeline.sql : stream + task graph for the full daily pipeline
-- All tasks are created SUSPENDED. To start the graph (children first, root last):
--   SELECT SYSTEM$TASK_DEPENDENTS_ENABLE('AI_FINOPS.DETECTION.TASK_DAILY_DETECTION');
--
--   TASK_DAILY_DETECTION (root, 06:00 UTC: Z-score)
--     ├── TASK_BUILD_INCIDENTS ── TASK_EXPLAIN_INCIDENTS (Cortex AI_COMPLETE)
--     └── TASK_ISOLATION_FOREST (only when new usage rows arrived; consumes the stream)

CREATE STREAM IF NOT EXISTS AI_FINOPS.RAW.SYNTHETIC_USAGE_STREAM
    ON TABLE AI_FINOPS.RAW.SYNTHETIC_USAGE
    COMMENT = 'New usage rows since the last Isolation Forest retrain';

CREATE TABLE IF NOT EXISTS AI_FINOPS.DETECTION.STREAM_CONSUMPTION_LOG (
    CONSUMED_AT  TIMESTAMP_LTZ,
    NEW_ROWS     NUMBER
);

-- Root task already exists (06_tasks.sql); it must be suspended to add children.
ALTER TASK IF EXISTS AI_FINOPS.DETECTION.TASK_DAILY_DETECTION SUSPEND;

CREATE TASK IF NOT EXISTS AI_FINOPS.DETECTION.TASK_BUILD_INCIDENTS
    WAREHOUSE = COMPUTE_WH
    COMMENT = 'Group anomalies into incidents and assign deterministic root cause'
    AFTER AI_FINOPS.DETECTION.TASK_DAILY_DETECTION
AS
    CALL AI_FINOPS.DETECTION.SP_BUILD_INCIDENTS();

CREATE TASK IF NOT EXISTS AI_FINOPS.DETECTION.TASK_EXPLAIN_INCIDENTS
    WAREHOUSE = COMPUTE_WH
    COMMENT = 'Cortex explanations for incidents that have none yet'
    AFTER AI_FINOPS.DETECTION.TASK_BUILD_INCIDENTS
AS
    CALL AI_FINOPS.DETECTION.SP_EXPLAIN_INCIDENTS(FALSE);

CREATE TASK IF NOT EXISTS AI_FINOPS.DETECTION.TASK_ISOLATION_FOREST
    WAREHOUSE = COMPUTE_WH
    COMMENT = 'Retrain Isolation Forest only when new usage arrived'
    AFTER AI_FINOPS.DETECTION.TASK_DAILY_DETECTION
    WHEN SYSTEM$STREAM_HAS_DATA('AI_FINOPS.RAW.SYNTHETIC_USAGE_STREAM')
AS
EXECUTE IMMEDIATE $$
BEGIN
    CALL AI_FINOPS.DETECTION.SP_DETECT_ISOLATION_FOREST(0.05, 30);
    -- reading the stream in DML advances its offset
    INSERT INTO AI_FINOPS.DETECTION.STREAM_CONSUMPTION_LOG
        SELECT CURRENT_TIMESTAMP(), COUNT(*) FROM AI_FINOPS.RAW.SYNTHETIC_USAGE_STREAM;
END;
$$;
